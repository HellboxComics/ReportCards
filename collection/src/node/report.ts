/** Writers for the published rarity report (collection/preview/RARITY.md) and rarity.json. */
import { STATUS_BY_KEY } from "../../copy/traits";
import { LAYERS, SUBJECT_KEYS, SUBJECT_NAMES, TIERS, type LayerKey } from "../catalog";
import { GENERATIVE_COUNT } from "../constants";
import { rarityTable, TOKEN_TIER_COUNTS } from "../rarity";
import type { GenerativeToken, Selection } from "../select";
import { visibleTraits } from "../traits";

const pct = (c: number, n = GENERATIVE_COUNT) => `${((c / n) * 100).toFixed(1)}%`;

/** Share of generated tokens per tier, for one layer. */
export function layerTierShares(sel: Selection, layer: LayerKey): Record<string, number> {
  const out: Record<string, number> = {};
  const def = LAYERS[layer];
  for (const q of sel.quotas[layer]) {
    const v = def.values.find((x) => x.id === q.valueId)!;
    out[v.tier] = (out[v.tier] ?? 0) + q.count / GENERATIVE_COUNT;
  }
  return out;
}

export function rarityJson(sel: Selection) {
  const table = rarityTable(sel);
  return {
    seed: sel.seed,
    method: "score = sum over visible traits of 1 / (count / 3300); rank by score desc, ties by id asc; 1/1s hold ranks 1-33",
    tokenTiers: Object.fromEntries(TOKEN_TIER_COUNTS),
    oneOfOnes: sel.oneOfOneIds,
    traitCounts: table.counts,
    layers: Object.fromEntries(
      (Object.keys(sel.quotas) as LayerKey[]).map((k) => [
        LAYERS[k].traitType,
        sel.quotas[k].map((q) => {
          const v = LAYERS[k].values.find((x) => x.id === q.valueId)!;
          return { id: q.valueId, name: v.name, tier: v.tier, target: q.target, count: q.count };
        }),
      ]),
    ),
    tokens: table.byId.map((r) => ({ id: r.id, rank: r.rank, tier: r.tier, score: r.score })),
  };
}

export function rarityMarkdown(sel: Selection): string {
  const table = rarityTable(sel);
  const gens = sel.tokens.filter((t): t is GenerativeToken => t.kind === "generative");
  const L: string[] = [];
  L.push("# Report Cards — the rarity curve");
  L.push("");
  L.push(`Generated by \`npm run collection:generate\` for seed \`${sel.seed}\`. Do not edit by hand.`);
  L.push("");
  L.push("![Rarity curve](./rarity-curve.png)");
  L.push("");
  L.push("## Token tiers (exact)");
  L.push("");
  L.push("Every generated card gets a statistical rarity score: the sum, over its 18 visible traits, of 1 / frequency. Cards are ranked by score and cut into tiers at exact counts. The 33 one-of-ones sit above everything as **1 of 1** (ranks 1–33).");
  L.push("");
  L.push("| Tier | Cards | Share of 3,300 | Rank range | Score range |");
  L.push("| ---- | ----: | ----: | ---- | ---- |");
  L.push(`| 1 of 1 | 33 | — | 1–33 | hand-made |`);
  for (const [tier, count] of TOKEN_TIER_COUNTS) {
    const rows = table.byId.filter((r) => r.tier === tier);
    const ranks = rows.map((r) => r.rank);
    const scores = rows.map((r) => r.score!);
    L.push(`| ${tier} | ${count} | ${pct(count)} | ${Math.min(...ranks)}–${Math.max(...ranks)} | ${Math.min(...scores).toFixed(1)}–${Math.max(...scores).toFixed(1)} |`);
  }
  L.push("");
  L.push("## Status curve (exact quotas)");
  L.push("");
  L.push("| Status | Cards | Share | Trait tier |");
  L.push("| ------ | ----: | ----: | ---------- |");
  for (const q of sel.quotas.status) {
    const v = LAYERS.status.values.find((x) => x.id === q.valueId)!;
    L.push(`| ${v.name} | ${q.count} | ${pct(q.count)} | ${v.tier} |`);
  }
  L.push("");
  L.push("## Every layer");
  L.push("");
  L.push("`target` is the designed quota from the tier curve; `count` is what this seed allocated (a conditional value is capped at 60% of the cards its rules allow, and the difference goes to that layer's unconditional values).");
  for (const k of ["background", "paper", "school", "season", "attendance", "penMarks", "doodle", "stain", "signature", "incident", "comment"] as LayerKey[]) {
    const def = LAYERS[k];
    const shares = layerTierShares(sel, k);
    L.push("");
    L.push(`### ${k === "season" ? "Semester season" : def.traitType}`);
    L.push("");
    L.push(`Tier shares: ${TIERS.filter((t) => shares[t]).map((t) => `${t} ${(shares[t] * 100).toFixed(1)}%`).join(" · ")}`);
    L.push("");
    L.push("| Value | Tier | Target | Count | Share |");
    L.push("| ----- | ---- | -----: | ----: | ----: |");
    const rows = sel.quotas[k]
      .map((q) => ({ q, v: def.values.find((x) => x.id === q.valueId)! }))
      .sort((a, b) => b.q.count - a.q.count);
    for (const { q, v } of rows) L.push(`| ${v.name.replace(/\|/g, "\\|")} | ${v.tier} | ${q.target} | ${q.count} | ${pct(q.count)} |`);
  }
  L.push("");
  L.push("## Grades (rule-driven, not rolled)");
  L.push("");
  L.push("Grades come from each card's status: six scores are generated so the app's own `determineStatus` (src/lib/grading.ts) prints exactly the allocated status. Letter counts per subject:");
  L.push("");
  const letters = ["A+", "A", "A-", "B+", "B", "B-", "C+", "C", "C-", "D+", "D", "D-", "F", "I"];
  L.push(`| Subject | ${letters.join(" | ")} |`);
  L.push(`| ------- | ${letters.map(() => "--:").join(" | ")} |`);
  for (const k of SUBJECT_KEYS) {
    const c = table.counts[SUBJECT_NAMES[k]] ?? {};
    L.push(`| ${SUBJECT_NAMES[k]} | ${letters.map((l) => c[l] ?? 0).join(" | ")} |`);
  }
  L.push("");
  L.push("## The 20 rarest generated cards");
  L.push("");
  L.push("| Rank | Token | Tier | Score | Status | Why |");
  L.push("| ---: | ----: | ---- | ----: | ------ | --- |");
  const top = table.byId.filter((r) => r.score !== null).sort((a, b) => a.rank - b.rank).slice(0, 20);
  for (const r of top) {
    const t = gens.find((g) => g.id === r.id)!;
    const rare = visibleTraits(t)
      .map(([type, value]) => ({ type, value, c: table.counts[type][value] }))
      .sort((a, b) => a.c - b.c)
      .slice(0, 2)
      .map((x) => `${x.type}: ${x.value} (${x.c})`)
      .join("; ");
    L.push(`| ${r.rank} | #${r.id} | ${r.tier} | ${r.score!.toFixed(1)} | ${STATUS_BY_KEY[t.status].name} | ${rare.replace(/\|/g, "\\|")} |`);
  }
  L.push("");
  L.push("## One-of-ones");
  L.push("");
  L.push("| Rank | Token | Title |");
  L.push("| ---: | ----: | ----- |");
  for (const r of table.byId.filter((x) => x.tier === "1 of 1").sort((a, b) => a.rank - b.rank)) {
    const t = sel.tokens[r.id - 1];
    if (t.kind === "oneOfOne") L.push(`| ${r.rank} | #${r.id} | ${t.piece.title} |`);
  }
  L.push("");
  return L.join("\n");
}
